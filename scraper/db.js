import { createClient } from '@supabase/supabase-js';

function getClient() {
  const url = process.env.SUPABASE_URL || process.env.VITE_SUPABASE_URL;
  // Prefer service role key for server-side writes (bypasses RLS)
  const key = process.env.SUPABASE_SERVICE_ROLE_KEY
    || process.env.SUPABASE_ANON_KEY
    || process.env.VITE_SUPABASE_ANON_KEY;
  if (!url || !key) throw new Error('SUPABASE_URL and SUPABASE_SERVICE_ROLE_KEY must be set in .env');
  return createClient(url, key);
}

let _supabase;
const supabase = new Proxy({}, {
  get(_, prop) {
    _supabase = _supabase ?? getClient();
    return _supabase[prop];
  },
});

// Schedule fields that change between scrapes and must stay fresh on every run.
// Everything else (incl. the enriched name_en/description_en/lat/long added
// later by the backfills) is left untouched when a row already exists.
const VOLATILE_FIELDS = [
  'next_dates', 'time_start', 'time_end',
  'schedule_type', 'schedule_label', 'price', 'price_notes',
];

/**
 * Fetch the set of source_urls already stored. Used by the scraper to skip the
 * paid Claude classify/translate call for items it already has — a brand-new
 * source_url is the only thing that needs an AI round-trip. One query per run.
 */
export async function getExistingSourceUrls() {
  const urls = new Set();
  const pageSize = 1000;
  for (let from = 0; ; from += pageSize) {
    const { data, error } = await supabase
      .from('activities')
      .select('source_url')
      .range(from, from + pageSize - 1);
    if (error) throw error;
    for (const row of data) if (row.source_url) urls.add(row.source_url);
    if (data.length < pageSize) break;
  }
  return urls;
}

// Merge two DATE[] lists into a sorted, de-duplicated, future-only set.
// Keeps recurring classes' upcoming sessions together when the same class
// arrives under a different source_url (a new SmartTicket per-session id, etc.).
function mergeNextDates(existing = [], incoming = []) {
  const today = new Date().toISOString().slice(0, 10);
  const set = new Set([...(existing || []), ...(incoming || [])].filter(d => d && d >= today));
  return [...set].sort().slice(0, 8);
}

// Refresh the volatile schedule fields on an existing row (shared by the
// source_url-match and content-match paths). Never touches name_en/translations.
async function refreshVolatile(id, activity, { mergeDates = false, existingDates = [] } = {}) {
  const patch = {};
  for (const f of VOLATILE_FIELDS) {
    if (f === 'next_dates') continue;
    if (activity[f] !== undefined) patch[f] = activity[f];
  }
  if (mergeDates) {
    patch.next_dates = mergeNextDates(existingDates, activity.next_dates);
  } else if (activity.next_dates !== undefined) {
    patch.next_dates = activity.next_dates;
  }
  if (Object.keys(patch).length) {
    const { error } = await supabase.from('activities').update(patch).eq('id', id);
    if (error) throw error;
  }
}

/**
 * Insert an activity, or fold it into an existing one. Three outcomes:
 *
 * 1. Same source_url already stored → refresh volatile schedule fields only,
 *    return null. (Recurring class re-seen at its stable URL.)
 * 2. Different source_url but the SAME class (matched on the content dedup key
 *    `name | venue | city` via the match_activity_id RPC) → merge its session
 *    date into the existing row's next_dates and refresh volatile fields,
 *    WITHOUT overwriting the existing name_en/translations. Return null.
 *    This is what stops transliteration-variant duplicates from piling up.
 * 3. Genuinely new → insert. The dedup_key column is generated by Postgres.
 */
export async function insertIfNew(activity) {
  // (1) exact source_url match
  const { data: existing } = await supabase
    .from('activities')
    .select('id, next_dates')
    .eq('source_url', activity.source_url)
    .maybeSingle();

  if (existing) {
    await refreshVolatile(existing.id, activity);
    return null;
  }

  // (2) content match — same class under a different URL. The dedup key is
  // `normalized-name | city` (venue is deliberately excluded — see migration
  // v14 — because sources spell the venue inconsistently across versions).
  const { data: matchId, error: rpcErr } = await supabase.rpc('match_activity_id', {
    p_name: activity.name ?? '',
    p_location: activity.location ?? '',
  });
  if (rpcErr) throw rpcErr;

  if (matchId) {
    const { data: dupe } = await supabase
      .from('activities')
      .select('id, next_dates')
      .eq('id', matchId)
      .maybeSingle();
    if (dupe) {
      await refreshVolatile(dupe.id, activity, { mergeDates: true, existingDates: dupe.next_dates });
      return null;
    }
  }

  // (3) brand-new class
  const { data, error } = await supabase
    .from('activities')
    .insert(activity)
    .select()
    .single();

  if (error) throw error;
  return data;
}
